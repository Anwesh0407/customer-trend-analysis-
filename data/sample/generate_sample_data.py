def main():
    # Save products JSON
    with open("data/sample/sample_kurtas.json", "w", encoding="utf-8") as f:
        json.dump(SAMPLE_PRODUCTS, f, indent=2)

    # Save products CSV
    with open("data/sample/sample_kurtas.csv", "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=list(SAMPLE_PRODUCTS[0].keys()))
        writer.writeheader()
        for p in SAMPLE_PRODUCTS:
            row = dict(p)
            row["available_sizes"] = ",".join(row["available_sizes"])
            writer.writerow(row)

    # Save reviews JSON
    with open("data/sample/sample_reviews.json", "w", encoding="utf-8") as f:
        json.dump(SAMPLE_REVIEWS, f, indent=2)

    # Save reviews CSV
    with open("data/sample/sample_reviews.csv", "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=list(SAMPLE_REVIEWS[0].keys()))
        writer.writeheader()
        writer.writerows(SAMPLE_REVIEWS)

    print(f"Generated {len(SAMPLE_PRODUCTS)} sample products and {len(SAMPLE_REVIEWS)} reviews.")

if __name__ == "__main__":
    main()
